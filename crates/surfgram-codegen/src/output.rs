use crate::codegen::GeneratedFile;
use std::fs;
use std::path::Path;

const HEADER: &str = "// Auto-generated by surfgram-codegen. Do not edit by paws.\n";

const LINTS: &str = "non_camel_case_types, non_snake_case, unused_imports, dead_code, clippy::all";

pub fn render(file: &GeneratedFile) -> Result<String, String> {
    let parsed: syn::File = syn::parse2(file.tokens.clone()).map_err(|e| {
        format!(
            "generated code for {} is not valid Rust: {e}",
            file.path.display()
        )
    })?;
    Ok(format!(
        "{HEADER}{}{}",
        file.preamble,
        prettyplease::unparse(&parsed)
    ))
}

pub fn write_files(dir: &Path, files: &[GeneratedFile]) -> Result<(), String> {
    if dir.exists() {
        fs::remove_dir_all(dir).map_err(|e| format!("failed to clean {}: {e}", dir.display()))?;
    }
    for file in files {
        let text = render(file)?;
        let path = dir.join(&file.path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)
                .map_err(|e| format!("failed to create {}: {e}", parent.display()))?;
        }
        fs::write(&path, text).map_err(|e| format!("failed to write {}: {e}", path.display()))?;
    }
    Ok(())
}

pub fn write_api_root(out_dir: &Path, api_dir: &Path) -> Result<(), String> {
    let mut text = HEADER.to_string();
    for (module, file) in [
        ("types", "types/mod.rs"),
        ("methods", "methods/mod.rs"),
        ("bot", "bot.rs"),
        ("errors", "errors.rs"),
    ] {
        let path = api_dir.join(file).display().to_string();
        text.push_str(&format!(
            "#[allow({LINTS})]\n#[path = {path:?}]\npub mod {module};\n"
        ));
    }
    let target = out_dir.join("api.rs");
    fs::write(&target, text).map_err(|e| format!("failed to write {}: {e}", target.display()))
}